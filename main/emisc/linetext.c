static uint32_t decode_utf8(const char **p) {
  return eos_utf8_decode_next(p);
}

uint32_t eos_linetext_measure(const char *utf8_text) {
  if (!utf8_text) return 0;
  uint32_t count = 0;
  const char *p = utf8_text;
  while (*p) {
    uint32_t cp = decode_utf8(&p);
    if (cp >= 32 && cp <= 126) {
      count++;
    }
  }
  return count * EOS_LINETEXT_FONT_W;
}

void eos_linetext_render_at(uint16_t *dst_rgb565, uint32_t buf_w, uint32_t buf_h,
                            const char *utf8_text, uint16_t fg_color,
                            bool center, uint32_t inset_x, int32_t start_y) {
  if (!dst_rgb565 || buf_w == 0 || buf_h == 0 || !utf8_text) return;

  uint32_t text_w = eos_linetext_measure(utf8_text);
  int32_t start_x = (int32_t)inset_x;
  if (center) {
    int32_t avail_w = (int32_t)buf_w - (int32_t)(2 * inset_x);
    if (avail_w > (int32_t)text_w) {
      start_x = (int32_t)inset_x + (avail_w - (int32_t)text_w) / 2;
    }
  }

  const char *p = utf8_text;
  int32_t cur_x = start_x;

  while (*p && cur_x < (int32_t)buf_w) {
    uint32_t cp = decode_utf8(&p);
    if (cp < 32 || cp > 126) continue; // Skip non-printable ASCII

    const uint8_t *glyph = s_font8x12[cp - 32];
    for (int r = 0; r < EOS_LINETEXT_FONT_H; r++) {
      int32_t py = start_y + r;
      if (py < 0 || py >= (int32_t)buf_h) break;

      uint8_t row_bits = glyph[r];
      for (int c = 0; c < EOS_LINETEXT_FONT_W; c++) {
        int32_t px = cur_x + c;
        if (px >= 0 && px < (int32_t)buf_w) {
          if (row_bits & (0x80 >> c)) {
            dst_rgb565[py * buf_w + px] = fg_color;
          }
        }
      }
    }
    cur_x += EOS_LINETEXT_FONT_W;
  }
}

void eos_linetext_render(uint16_t *dst_rgb565, uint32_t buf_w, uint32_t buf_h,
                         const char *utf8_text, uint16_t fg_color, uint16_t bg_color,
                         bool center, uint32_t inset_x) {
  if (!dst_rgb565 || buf_w == 0 || buf_h == 0) return;

  // Fill background
  for (uint32_t i = 0; i < buf_w * buf_h; i++) {
    dst_rgb565[i] = bg_color;
  }

  if (!utf8_text) return;

  int32_t start_y = ((int32_t)buf_h - (int32_t)EOS_LINETEXT_FONT_H) / 2;
  if (start_y < 0) start_y = 0;

  eos_linetext_render_at(dst_rgb565, buf_w, buf_h, utf8_text, fg_color, center, inset_x, start_y);
}
