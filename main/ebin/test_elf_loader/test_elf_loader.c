static bool helper_write_file(const char *path, const void *buf, size_t len) {
  FILE *f = fopen(path, "wb");
  if (!f) return false;
  size_t w = fwrite(buf, 1, len, f);
  fclose(f);
  return (w == len);
}

static bool helper_file_contains(const char *path, const char *substr) {
  FILE *f = fopen(path, "rb");
  if (!f) return false;
  char buf[512];
  size_t n = fread(buf, 1, sizeof(buf) - 1, f);
  fclose(f);
  buf[n] = 0;
  return (strstr(buf, substr) != NULL);
}

int test_elf_loader_main(int argc, char **argv) {
  (void)argc;
  (void)argv;
  printf("\n=== Running Dynamic ELF Loader Test Suite ===\n");
  test_ctx_t ctx = {0, 0};

  // Node names in tmpfs must be < TMP_NODE_NAME_MAX (16 bytes)
  const char *elf_path = "/tmp/hello.elf";
  const char *out_path = "/tmp/out1.txt";
  const char *out_rel_path = "/tmp/out2.txt";
  const char *out_env_path = "/tmp/out3.txt";
  const char *txt_path = "/tmp/not_elf.txt";

  // 1. Stage sample relocatable ELF binary into /tmp
  bool written = helper_write_file(elf_path, s_sample_elf, sizeof(s_sample_elf));
  report_test(&ctx, "elf_loader: write relocatable ELF binary to /tmp", written);

  bool txt_written = helper_write_file(txt_path, "Plain text, not ELF\n", 20);
  report_test(&ctx, "elf_loader: write non-ELF test file to /tmp", txt_written);

  // 2. ELF header detection tests
  report_test(&ctx, "elf_loader: eos_is_elf_file(valid_elf) == true",
              eos_is_elf_file(elf_path));
  report_test(&ctx, "elf_loader: eos_is_elf_file(plain_text) == false",
              !eos_is_elf_file(txt_path));
  report_test(&ctx, "elf_loader: eos_is_elf_file(nonexistent) == false",
              !eos_is_elf_file("/tmp/nonexistent.elf"));

  // 3. Absolute path execution with arguments and redirection
  unlink(out_path);
  int ret_abs = system("/tmp/hello.elf alpha beta > /tmp/out1.txt");
  report_test(&ctx, "elf_loader: execute via absolute path returns 0", ret_abs == 0);
  report_test(&ctx, "elf_loader: verify app greeting in stdout",
              helper_file_contains(out_path, "Hello from EOS dynamic ELF app: /tmp/hello.elf!"));
  report_test(&ctx, "elf_loader: verify argv[1] = alpha in stdout",
              helper_file_contains(out_path, "argv[1] = alpha"));
  report_test(&ctx, "elf_loader: verify argv[2] = beta in stdout",
              helper_file_contains(out_path, "argv[2] = beta"));

  // 4. Relative path execution (./hello.elf) from cwd
  char orig_cwd[256];
  if (getcwd(orig_cwd, sizeof(orig_cwd)) != NULL) {
    chdir("/tmp");
    unlink(out_rel_path);
    int ret_rel = system("./hello.elf gamma > /tmp/out2.txt");
    report_test(&ctx, "elf_loader: execute via ./ relative path returns 0", ret_rel == 0);
    report_test(&ctx, "elf_loader: verify argv[1] = gamma in stdout",
                helper_file_contains(out_rel_path, "argv[1] = gamma"));
    chdir(orig_cwd);
  }

  // 5. Environment $PATH resolution
  char old_path[64];
  const char *cur_p = getenv("PATH");
  strlcpy(old_path, cur_p ? cur_p : "/bin", sizeof(old_path));

  setenv("PATH", "/tmp:/bin", 1);
  unlink(out_env_path);
  int ret_env = system("hello.elf delta > /tmp/out3.txt");
  report_test(&ctx, "elf_loader: execute via $PATH directory lookup returns 0", ret_env == 0);
  report_test(&ctx, "elf_loader: verify argv[1] = delta in stdout",
              helper_file_contains(out_env_path, "argv[1] = delta"));
  setenv("PATH", old_path, 1);

  // 6. Cleanup temporary files
  unlink(elf_path);
  unlink(txt_path);
  unlink(out_path);
  unlink(out_rel_path);
  unlink(out_env_path);

  printf("\nDynamic ELF Loader Tests: %d passed, %d failed\n\n", ctx.passed, ctx.failed);
  return (ctx.failed == 0) ? 0 : 1;
}

